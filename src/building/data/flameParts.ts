// 哪些部位不能上星火（追加屬性）。
//
// 一度拿潛能的部位表當代用品，那是錯的：口袋道具有星火卻沒有潛能欄，
// 機器心臟有潛能卻不能上星火 —— 兩份名單互有出入，不能互相推。
//
// 這裡採「預設可以、列出不行的」：漏列一個不能上的，玩家會多看到一個沒用的欄位；
// 反過來把能上的擋掉，玩家就沒辦法做出自己實際擁有的裝備了，後者嚴重得多。

/**
 * 不能上星火的部位。
 *
 * 機器心臟是遊戲內 tooltip 直接寫「追加屬性 無法強化」確認的。
 * 其餘幾個是沒有追加屬性欄的特殊欄位，同步下來的裝備也都沒有星火數值。
 */
export const NO_FLAME_PARTS: ReadonlySet<string> = new Set([
  '機器心臟',
  '胸章',
  '徽章',
  '勳章',
  '圖騰',
  '寶石',
  '輔助特殊技能戒指',
])

export function canFlame(part: string): boolean {
  return !NO_FLAME_PARTS.has(part)
}
